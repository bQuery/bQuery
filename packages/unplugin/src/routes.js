/**
 * File routes: a virtual module (`virtual:bquery/routes`) that builds the route
 * table from the files under a directory, replacing hand-written
 * `import.meta.glob` wiring.
 *
 * @module @bquery/unplugin/routes
 */

import path from 'node:path';
import { parseFilePath } from '@bquery/bquery/router';
import { createFilter, toPosix, walkFiles } from './utils.js';

/** Public id of the file-routes virtual module. */
export const ROUTES_MODULE_ID = 'virtual:bquery/routes';

/** Default directory scanned for route files (relative to the project root). */
export const DEFAULT_ROUTES_DIR = 'src/routes';

/** Default extensions of route modules. */
export const DEFAULT_ROUTE_EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx', '.mjs'];

/**
 * Returns the id a virtual module resolves to for the current bundler. Rollup
 * and Vite use the `\0` convention; esbuild needs a path-like id in an existing
 * directory (its `resolveDir`) so imports inside the module resolve from the
 * project root. The file never exists on disk.
 *
 * @param {string} name - Public virtual id (e.g. `virtual:bquery/routes`).
 * @param {{ root: string, framework: string }} shared - Shared plugin state.
 * @returns {string} The resolved id.
 */
export const resolvedVirtualId = (name, shared) =>
  shared.framework === 'esbuild'
    ? `${toPosix(shared.root)}/__${name.replace(/[:/]/g, '_')}.js`
    : `\0${name}`;

/**
 * Lists the route files under the configured directory and converts them into
 * manifest records.
 *
 * @param {object} options - Normalised file-route options.
 * @param {string} root - Project root.
 * @returns {Promise<Array<{ key: string, file: string, kind: string, pattern: string }>>}
 *   One record per page/layout file (server-only `+server` files are skipped).
 */
export const scanRouteFiles = async (options, root) => {
  const dir = path.resolve(root, options.dir ?? DEFAULT_ROUTES_DIR);
  const routesDir = toPosix(path.relative(root, dir));
  const extensions = options.extensions ?? DEFAULT_ROUTE_EXTENSIONS;
  const excluded = options.exclude ? createFilter(root, options.exclude) : () => false;
  const records = [];
  for (const file of await walkFiles(dir)) {
    if (!extensions.some((ext) => file.endsWith(ext)) || file.endsWith('.d.ts')) continue;
    if (excluded(file)) continue;
    const key = `/${toPosix(path.relative(root, file))}`;
    const parsed = parseFilePath(key, {
      routesDir,
      pageFiles: options.pageFiles,
      layoutFiles: options.layoutFiles,
    });
    if (!parsed || parsed.kind === 'server') continue;
    records.push({ key, file: toPosix(file), kind: parsed.kind, pattern: parsed.pattern });
  }
  return records;
};

/**
 * Generates the source of `virtual:bquery/routes`.
 *
 * @param {Array<{ key: string, file: string, kind: string, pattern: string }>} records
 *   Route files from {@link scanRouteFiles}.
 * @param {object} options - Normalised file-route options.
 * @param {string} root - Project root.
 * @returns {string} ES module source.
 */
export const generateRoutesModule = (records, options, root) => {
  const routesDir = toPosix(
    path.relative(root, path.resolve(root, options.dir ?? DEFAULT_ROUTES_DIR))
  );
  const routerImport = options.routerImport ?? '@bquery/bquery/router';
  const eager = options.eager === true;
  const imports = [];
  const valueFor = (record, index) => {
    if (!eager) return `() => import(${JSON.stringify(record.file)})`;
    imports.push(`import * as __bq_route_${index} from ${JSON.stringify(record.file)};`);
    return `__bq_route_${index}`;
  };

  const manifestLines = [];
  const layoutLines = [];
  records.forEach((record, index) => {
    const value = valueFor(record, index);
    manifestLines.push(`  ${JSON.stringify(record.key)}: ${value},`);
    if (record.kind === 'layout')
      layoutLines.push(`  ${JSON.stringify(record.pattern)}: ${value},`);
  });

  const createOptions = { routesDir };
  if (options.pageFiles) createOptions.pageFiles = options.pageFiles;
  if (options.layoutFiles) createOptions.layoutFiles = options.layoutFiles;

  return [
    '// Generated by @bquery/unplugin (file routes). Do not edit.',
    `import { createFileRoutes } from ${JSON.stringify(routerImport)};`,
    ...imports,
    '',
    `export const manifest = {\n${manifestLines.join('\n')}\n};`,
    `export const layouts = {\n${layoutLines.join('\n')}\n};`,
    `export const options = ${JSON.stringify(createOptions)};`,
    'const result = createFileRoutes(manifest, options);',
    'export const routes = result.routes;',
    'export const entries = result.entries;',
    'export default routes;',
    '',
  ].join('\n');
};

/**
 * Invalidates a virtual module in every Vite module graph (Vite 6+
 * environments, with a fallback for the legacy single graph).
 *
 * @param {any} server - Vite dev server.
 * @param {string} id - Resolved module id.
 * @returns {boolean} Whether a loaded module was invalidated.
 */
export const invalidateViteModule = (server, id) => {
  let found = false;
  const graphs = server.environments
    ? Object.values(server.environments).map((env) => env.moduleGraph)
    : [server.moduleGraph];
  for (const graph of graphs) {
    const mod = graph?.getModuleById?.(id);
    if (mod) {
      graph.invalidateModule(mod);
      found = true;
    }
  }
  return found;
};

/**
 * Sends a full page reload to connected Vite clients.
 *
 * @param {any} server - Vite dev server.
 */
export const viteFullReload = (server) => {
  const channel = server.hot ?? server.ws;
  channel?.send?.({ type: 'full-reload', path: '*' });
};

/**
 * Creates the `bquery:routes` plugin.
 *
 * @param {object} options - File-route options (see `FileRoutesOptions`).
 * @param {{ root: string, framework: string }} shared - Shared plugin state.
 * @returns {import('unplugin').UnpluginOptions} The plugin.
 */
export const createRoutesPlugin = (options, shared) => {
  const resolvedId = () => resolvedVirtualId(ROUTES_MODULE_ID, shared);
  const isRouteFile = (file) => {
    const dir = path.resolve(shared.root, options.dir ?? DEFAULT_ROUTES_DIR);
    const rel = path.relative(dir, file);
    if (rel.startsWith('..') || path.isAbsolute(rel)) return false;
    return (options.extensions ?? DEFAULT_ROUTE_EXTENSIONS).some((ext) => file.endsWith(ext));
  };

  return {
    name: 'bquery:routes',
    resolveId(source) {
      return source === ROUTES_MODULE_ID ? resolvedId() : null;
    },
    loadInclude(id) {
      return id === resolvedId();
    },
    async load(id) {
      if (id !== resolvedId()) return null;
      const records = await scanRouteFiles(options, shared.root);
      for (const record of records) this.addWatchFile?.(record.file);
      return { code: generateRoutesModule(records, options, shared.root), map: null };
    },
    vite: {
      configureServer(server) {
        const onAddOrRemove = (file) => {
          if (!isRouteFile(file)) return;
          if (invalidateViteModule(server, resolvedId())) viteFullReload(server);
          options.onUpdate?.(file);
        };
        server.watcher.on('add', onAddOrRemove);
        server.watcher.on('unlink', onAddOrRemove);
      },
    },
  };
};
