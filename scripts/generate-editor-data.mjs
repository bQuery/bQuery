#!/usr/bin/env bun
/**
 * Generate editor IntelliSense data from the sources (#227):
 *
 * - `editor/html-custom-data.json` — VS Code HTML custom data for every
 *   built-in `bq-*` directive, generated from `src/view/directive-registry.ts`.
 * - `editor/bquery-config.schema.json` — a JSON Schema for the object passed
 *   to `defineBqueryConfig()`, generated from the `BqueryConfig` interface in
 *   `src/platform/config.ts` with the TypeScript compiler API.
 *
 * Usage:
 *   bun scripts/generate-editor-data.mjs          # write the files
 *   bun scripts/generate-editor-data.mjs --check  # fail if they are stale
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DOCS_BASE = 'https://bquery.js.org/guide/view';
const PACKAGE_NAME = '@bquery/bquery';

/** Events offered as ready-made `bq-on:<event>` attributes. */
export const COMMON_EVENTS = [
  'blur',
  'change',
  'click',
  'dblclick',
  'focus',
  'input',
  'keydown',
  'keyup',
  'mouseenter',
  'mouseleave',
  'pointerdown',
  'pointerup',
  'submit',
];

/** Attributes offered as ready-made `bq-bind:<attribute>` attributes. */
export const COMMON_BIND_ATTRIBUTES = [
  'alt',
  'checked',
  'class',
  'disabled',
  'hidden',
  'href',
  'id',
  'placeholder',
  'readonly',
  'src',
  'title',
  'type',
  'value',
];

const reference = (info) => [{ name: 'bQuery view guide', url: `${DOCS_BASE}#${info.docs}` }];

const attributeEntry = (name, info, description = info.description) => {
  const entry = { name, description: { kind: 'markdown', value: description } };
  if (info.value === 'none') entry.valueSet = 'v';
  if (info.values?.length) entry.values = info.values.map((value) => ({ name: value }));
  entry.references = reference(info);
  return entry;
};

/** Build the VS Code custom data object from the directive registry. */
export const buildHtmlCustomData = (directives) => {
  const globalAttributes = [];
  for (const info of directives) {
    const prefixed = `bq-${info.name}`;
    if (info.argument === 'event') {
      for (const event of COMMON_EVENTS) {
        globalAttributes.push(
          attributeEntry(`${prefixed}:${event}`, info, `\`${event}\` event. ${info.description}`)
        );
      }
      continue;
    }
    if (info.argument === 'attribute') {
      for (const attribute of COMMON_BIND_ATTRIBUTES) {
        globalAttributes.push(
          attributeEntry(
            `${prefixed}:${attribute}`,
            info,
            `Binds \`${attribute}\`. ${info.description}`
          )
        );
      }
      continue;
    }
    globalAttributes.push(attributeEntry(prefixed, info));
  }
  return {
    $comment: `Generated by scripts/generate-editor-data.mjs from src/view/directive-registry.ts — do not edit by hand. Add to .vscode/settings.json: "html.customData": ["./node_modules/${PACKAGE_NAME}/editor/html-custom-data.json"]`,
    version: 1.1,
    globalAttributes,
  };
};

// ---------------------------------------------------------------------------
// JSON Schema from the BqueryConfig interface
// ---------------------------------------------------------------------------

const docOf = (node) => {
  const docs = ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc);
  const text = docs
    .map((doc) => ts.getTextOfJSDocComment(doc.comment) ?? '')
    .join('\n')
    .trim();
  return text || undefined;
};

/**
 * Convert a type node to a JSON Schema fragment. Returns `null` for types JSON
 * cannot represent (functions), so the property is left out of the schema.
 */
const typeToSchema = (node, interfaces) => {
  switch (node.kind) {
    case ts.SyntaxKind.StringKeyword:
      return { type: 'string' };
    case ts.SyntaxKind.NumberKeyword:
      return { type: 'number' };
    case ts.SyntaxKind.BooleanKeyword:
      return { type: 'boolean' };
    case ts.SyntaxKind.FunctionType:
      return null;
    case ts.SyntaxKind.ArrayType: {
      const items = typeToSchema(node.elementType, interfaces);
      return items ? { type: 'array', items } : null;
    }
    case ts.SyntaxKind.LiteralType:
      if (ts.isStringLiteral(node.literal)) return { const: node.literal.text };
      if (ts.isNumericLiteral(node.literal)) return { const: Number(node.literal.text) };
      throw new Error(`Unsupported literal type: ${node.getText()}`);
    case ts.SyntaxKind.UnionType: {
      const members = node.types.map((member) => typeToSchema(member, interfaces));
      if (members.every((member) => member && 'const' in member)) {
        return { enum: members.map((member) => member.const) };
      }
      return { anyOf: members.filter(Boolean) };
    }
    case ts.SyntaxKind.TypeReference: {
      const name = node.typeName.getText();
      if (name === 'HeadersInit') {
        return {
          description: 'Header name → value map, or a list of [name, value] pairs.',
          anyOf: [
            { type: 'object', additionalProperties: { type: 'string' } },
            {
              type: 'array',
              items: { type: 'array', items: { type: 'string' }, minItems: 2, maxItems: 2 },
            },
          ],
        };
      }
      if (interfaces.has(name)) return { $ref: `#/$defs/${name}` };
      throw new Error(`Unsupported type reference in BqueryConfig: ${name}`);
    }
    default:
      throw new Error(`Unsupported type in BqueryConfig: ${ts.SyntaxKind[node.kind]}`);
  }
};

const interfaceToSchema = (declaration, interfaces, aliases) => {
  const properties = {};
  for (const member of declaration.members) {
    if (!ts.isPropertySignature(member) || !member.type) continue;
    const name = member.name.getText();
    const resolvedType = ts.isTypeReferenceNode(member.type)
      ? (aliases.get(member.type.typeName.getText()) ?? member.type)
      : member.type;
    const schema = typeToSchema(resolvedType, interfaces);
    if (!schema) continue;
    const description = docOf(member);
    properties[name] = description ? { description, ...schema } : schema;
  }
  const schema = { type: 'object', additionalProperties: false, properties };
  const description = docOf(declaration);
  return description ? { description, ...schema } : schema;
};

/** Build the JSON Schema for `BqueryConfig` from `src/platform/config.ts`. */
export const buildConfigSchema = async () => {
  const file = resolve(repoRoot, 'src/platform/config.ts');
  const source = ts.createSourceFile(
    file,
    await readFile(file, 'utf8'),
    ts.ScriptTarget.Latest,
    true
  );
  const interfaces = new Map();
  const aliases = new Map();
  for (const statement of source.statements) {
    if (ts.isInterfaceDeclaration(statement)) interfaces.set(statement.name.text, statement);
    if (ts.isTypeAliasDeclaration(statement)) aliases.set(statement.name.text, statement.type);
  }
  const root = interfaces.get('BqueryConfig');
  if (!root) throw new Error('BqueryConfig not found in src/platform/config.ts');

  const $defs = {};
  for (const [name, declaration] of interfaces) {
    if (name !== 'BqueryConfig') $defs[name] = interfaceToSchema(declaration, interfaces, aliases);
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `https://unpkg.com/${PACKAGE_NAME}/editor/bquery-config.schema.json`,
    title: 'bQuery configuration',
    $comment:
      'Generated by scripts/generate-editor-data.mjs from the BqueryConfig interface — do not edit by hand. Function-valued options (pageMeta.titleTemplate) cannot be expressed in JSON and are omitted.',
    ...interfaceToSchema(root, interfaces, aliases),
    properties: {
      $schema: { type: 'string' },
      ...interfaceToSchema(root, interfaces, aliases).properties,
    },
    $defs,
  };
};

const format = async (value, filepath) => {
  const prettier = await import('prettier');
  const options = (await prettier.resolveConfig(filepath)) ?? {};
  return prettier.format(JSON.stringify(value), { ...options, filepath });
};

export const generateEditorData = async () => {
  const { BUILT_IN_DIRECTIVES } = await import('../src/view/directive-registry.ts');
  const htmlPath = resolve(repoRoot, 'editor/html-custom-data.json');
  const schemaPath = resolve(repoRoot, 'editor/bquery-config.schema.json');
  return [
    [htmlPath, await format(buildHtmlCustomData(BUILT_IN_DIRECTIVES), htmlPath)],
    [schemaPath, await format(await buildConfigSchema(), schemaPath)],
  ];
};

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const files = await generateEditorData();
  let stale = 0;
  for (const [path, content] of files) {
    const relative = path.slice(repoRoot.length + 1);
    if (check) {
      const current = await readFile(path, 'utf8').catch(() => '');
      if (current !== content) {
        console.error(`✗ ${relative} is out of date — run \`bun run generate:editor-data\`.`);
        stale++;
      }
      continue;
    }
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content);
    console.log(`✓ wrote ${relative}`);
  }
  if (check) {
    if (stale > 0) process.exit(1);
    console.log('✓ Editor data (html-custom-data.json, bquery-config.schema.json) is up to date.');
  }
}
